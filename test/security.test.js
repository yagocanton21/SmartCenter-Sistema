const { start } = require('./helpers');
const assert = require('node:assert/strict');
const { getDatabase } = require('../server/db/connection');
const { OS } = require('../server/models');
(async()=>{
  const {request,close,base}=await start();
  try {
    assert.equal((await request('GET','/api/db',undefined,{},true)).status,401);
    assert.equal((await request('POST','/api/save',{users:[]},{},true)).status,401);
    for (const file of ['/smartcenter.db','/data/smartcenter.db','/.env','/.git/config','/server.js','/server/routes/api.js','/package.json']) assert.equal((await request('GET',file)).status,404,file);
    assert.equal((await request('GET','/%FF')).status,400);
    assert.equal((await request('GET','/api/status')).status,200);
    assert.equal((await request('POST','/api/changes',{changes:[]},{'X-CSRF-Token':'invalid'})).status,403);
    assert.equal((await request('POST','/api/changes',{changes:[]},{Origin:'https://attacker.example'})).status,403);
    const db=(await request('GET','/api/db')).body.db;
    assert.ok(db.users.length); assert.ok(db.users.every(u=>!u.senha && !u.password));
    const auth=require('../server/security/auth');
    auth.save({id:'legacy',login:'legacy',nome:'Legado',perfil:'tecnico',perms:['os'],ativo:true,senha:'1a48e4cee4d6b2'});
    const legacy=await request('POST','/api/auth/login',{login:'legacy',password:'admin'},{},true);
    assert.equal(legacy.status,200);assert.equal(legacy.body.user.mustChangePassword,false);
    assert.ok(require('../server/models/Usuario').getById('legacy').senha.startsWith('scrypt:'));
    const user={id:'seller',login:'seller',nome:'Vendedor',perfil:'vendedor',perms:['dashboard','vendas','clientes'],ativo:true,password:'seller-test-password'};
    assert.equal((await request('POST','/api/changes',{changes:[{entity:'users',id:user.id,before:null,after:user}]})).status,200);
    const login=await request('POST','/api/auth/login',{login:'seller',password:user.password},{},true);
    assert.equal(login.status,200); assert.ok(login.headers.get('set-cookie').includes('HttpOnly'));
    const userHeaders={Cookie:login.headers.get('set-cookie').split(';')[0],'X-CSRF-Token':login.body.csrf};
    assert.equal((await request('GET','/api/db',undefined,userHeaders,true)).status,200);
    const shortUser={id:'short',login:'short',nome:'Curto',perfil:'vendedor',perms:['dashboard'],ativo:true,password:'1234'};
    assert.equal((await request('POST','/api/changes',{changes:[{entity:'users',id:shortUser.id,before:null,after:shortUser}]})).status,200);
    const shortLogin=await request('POST','/api/auth/login',{login:'short',password:'1234'},{},true);
    assert.equal(shortLogin.status,200);
    assert.equal((await request('POST','/api/auth/password',{currentPassword:user.password,password:'seller-new-password'},userHeaders,true)).status,200);
    assert.equal((await request('POST','/api/changes',{changes:[{entity:'config',id:'nomeFantasia',before:null,after:'Invadido'}]},userHeaders,true)).status,403);
    assert.equal((await request('GET','/api/backup',undefined,userHeaders,true)).status,403);
    OS.salvarOSTransacional({id:'private',status:'Recebido',aparelho:{senha:'SECRET-PIN-2718',senhaPadrao:'12369'}});
    const stored=getDatabase().prepare('SELECT data FROM os WHERE id=?').get('private').data;
    assert.ok(!stored.includes('SECRET-PIN-2718')); assert.ok(!stored.includes('12369'));
    assert.equal(OS.getById('private').aparelho.senha,'SECRET-PIN-2718');
    const limited=(await request('GET','/api/db',undefined,userHeaders,true)).body.db;
    assert.equal(limited.os.length,0); assert.equal(limited.users.length,1); assert.equal(limited.log.length,0);
    const delivered=OS.getById('private'); delivered.status='Entregue'; OS.salvarOSTransacional(delivered);
    assert.equal(OS.getById('private').aparelho.senha,'');
    const backup=(await request('GET','/api/backup')).body;
    assert.ok(backup.users[0].senha.startsWith('scrypt:')); assert.equal(backup.os[0].aparelho.senha,'');
    const restore=await request('POST','/api/restore',backup);
    assert.equal(restore.status,200,JSON.stringify(restore.body));
    assert.equal((await request('GET','/api/db')).status,401);
    assert.equal((await request('GET','/api/db',undefined,userHeaders,true)).status,401);
    assert.equal((await request('POST','/api/auth/login',{login:'admin',password:'permanent-test-password'},{},true)).status,200);
    const response=await fetch(base+'/'); assert.equal(response.status,200);
    const html=await response.text();
    assert.ok(html.includes('js/remote.js'));
    assert.ok(html.includes('js/whats.js'));
    assert.ok(html.includes('js/notas.js'));
    assert.equal((await fetch(base+'/js/whats.js')).status,200);
    assert.equal((await fetch(base+'/js/notas.js')).status,200);
    console.log('OK: autenticação, troca obrigatória, CSRF, permissões, arquivos privados, URL inválida, criptografia, retenção e restauração.');
  } finally { await close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
